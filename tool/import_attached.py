def norm_name(n):
    n = n.strip()
    n = re.sub(r"\s*\(.*?\)\s*", "", n).strip()
    return n

wb = load_workbook(SRC)
ws = wb.active
rows = []
for r in list(ws.rows)[1:]:
    letter = (r[0].value or "").strip()
    name = (r[1].value or "").strip()
    if not name: continue
    rows.append({"letter": letter.upper(), "name": norm_name(name),
                 "raw": name, "cat": (r[2].value or "Treatable").strip(),
                 "remedies": (r[3].value or "").strip(),
                 "tests": (r[4].value or "").strip()})

def parse_tests(t):
    t = t.strip()
    if not t or t.lower() == "clinical evaluation":
        return ["Clinical Evaluation Required First"]
    return [x.strip() for x in re.split(r",|;", t) if x.strip()]

def parse_herbs(rem):
    ids, newids = [], []
    for tok in re.split(r"/", rem):
        key = tok.strip().lower()
        if not key or key not in HERB_MAP: 
            if key and key not in HERB_MAP: print("UNMAPPED HERB:", repr(tok))
            continue
        m = HERB_MAP[key]
        if m is None: continue
        (newids if m.startswith("NEW:") else ids).append(m[4:] if m.startswith("NEW:") else m)
    return ids, newids

